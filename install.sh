#!/usr/bin/env bash
# Install (or update) the IMAP spam filter as systemd *user* services.
#
#   ./install.sh              install / update; existing accounts are kept
#   ./install.sh --uninstall  stop all accounts and remove program + units
#                             (settings, encrypted passwords and data are kept)
#
# Nothing here needs root. Accounts are added afterwards with:
#   imap-spam-filter add <name>
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/imap-spam-filter"
CONF_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/imap-spam-filter"
STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/imap-spam-filter"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
BIN_DIR="$HOME/.local/bin"

# The classifier uses the NVIDIA-only Ollama (system ollama-cuda.service on 11435),
# so the main Ollama (11434) stays free for other work. Override with env vars if needed.
OLLAMA_BIN="${OLLAMA_BIN:-/usr/bin/ollama}"
SPAM_OLLAMA_URL="${SPAM_OLLAMA_URL:-http://127.0.0.1:11435}"
SPAM_FILTER_MODEL="${SPAM_FILTER_MODEL:-qwen3:4b}"

if [[ -t 1 ]]; then B=$'\e[1m' R=$'\e[31m' G=$'\e[32m' Y=$'\e[33m' C=$'\e[36m' N=$'\e[0m'; else B= R= G= Y= C= N=; fi
die()  { echo "${R}error:${N} $*" >&2; exit 1; }
info() { echo "${C}::${N} $*"; }
warn() { echo "${Y}warning:${N} $*"; }

UNITS=(imap-spam-filter@.service imap-spam-filter@.timer
       imap-spam-filter-learn@.service imap-spam-filter-learn@.timer)

# --------------------------------------------------------------------------- uninstall

if [[ "${1:-}" == --uninstall ]]; then
  for t in $(systemctl --user list-units --all --plain --no-legend 'imap-spam-filter*@*.timer' | awk '{print $1}'); do
    systemctl --user disable --now "$t" || true
  done
  for u in "${UNITS[@]}"; do rm -f "$UNIT_DIR/$u"; done
  rm -rf "$UNIT_DIR"/imap-spam-filter@*.timer.d "$APP_DIR" "$BIN_DIR/imap-spam-filter"
  systemctl --user daemon-reload
  info "uninstalled. Kept: $CONF_DIR (settings + encrypted passwords) and $STATE_DIR (data)"
  echo "   delete those too for a full wipe:  rm -rf '$CONF_DIR' '$STATE_DIR'"
  exit 0
fi

# --------------------------------------------------------------------------- checks

[[ $EUID -ne 0 ]] || die "run as your normal user, not root (these are user services)"
[[ -f "$SRC/spam_filter.py" && -f "$SRC/imap-spam-filter" ]] || die "run from the imap-spam-filter source folder"

PYTHON=$(command -v python3) || die "python3 not found"
"$PYTHON" -c 'import sys; sys.exit(sys.version_info < (3, 12))' \
  || die "Python 3.12+ required ($("$PYTHON" --version))"
command -v systemd-creds >/dev/null || die "systemd-creds not found (needs systemd 256+)"
command -v flock >/dev/null        || die "flock not found (util-linux)"
systemctl --user show-environment >/dev/null 2>&1 || die "no systemd user session (systemctl --user)"

# The whole point: can this user encrypt and decrypt a credential?
probe=$(printf probe | systemd-creds encrypt --user --name=probe - - 2>/dev/null \
        | systemd-creds decrypt --user --name=probe - - 2>/dev/null) || true
[[ "$probe" == probe ]] || die "systemd-creds --user encrypt/decrypt does not work here (needs systemd 256+ and TPM2 or a host key)"
if systemd-analyze has-tpm2 >/dev/null 2>&1; then info "TPM2 found - passwords will be bound to this machine's TPM"
else warn "no TPM2 - passwords are protected by the host key only (/var/lib/systemd/credential.secret)"; fi

HERMES=$(command -v hermes || true)  # optional: only for --backend hermes
[[ -x "$OLLAMA_BIN" ]] || die "ollama not found at $OLLAMA_BIN (set OLLAMA_BIN)"
command -v curl >/dev/null || die "curl not found"
curl -fsS -m 3 "$SPAM_OLLAMA_URL/api/version" >/dev/null 2>&1 \
  || die "Ollama is not answering on $SPAM_OLLAMA_URL - start it first (sudo systemctl enable --now ollama-cuda)"
[[ "$(loginctl show-user "$USER" -p Linger --value 2>/dev/null)" == yes ]] \
  || warn "lingering is off: checks only run while you are logged in. Enable with: loginctl enable-linger $USER"

# --------------------------------------------------------------------------- files

mkdir -p "$APP_DIR" "$UNIT_DIR" "$BIN_DIR"
mkdir -p -m 700 "$CONF_DIR" "$CONF_DIR/accounts" "$CONF_DIR/creds" "$STATE_DIR"
chmod 700 "$CONF_DIR" "$CONF_DIR/accounts" "$CONF_DIR/creds" "$STATE_DIR"

install -m 755 "$SRC/spam_filter.py"   "$APP_DIR/spam_filter.py"
install -m 755 "$SRC/imap-spam-filter" "$BIN_DIR/imap-spam-filter"
[[ -f "$SRC/README.md" ]] && install -m 644 "$SRC/README.md" "$APP_DIR/README.md"

# Services don't get your shell's PATH (mise, pipx, ...), so pin what they need.
SVC_PATH="$(dirname "$PYTHON")"
[[ -n "$HERMES" ]] && SVC_PATH="$(dirname "$HERMES"):$SVC_PATH"
SVC_PATH="$SVC_PATH:/usr/local/bin:/usr/bin:/bin"
umask 077
cat > "$CONF_DIR/service.env" <<EOF
# Shared settings for all accounts (regenerated by install.sh)
PATH="$SVC_PATH"
PYTHON="$PYTHON"
OLLAMA_URL="$SPAM_OLLAMA_URL"
SPAM_FILTER_MODEL="$SPAM_FILTER_MODEL"
EOF
umask 022

# --------------------------------------------------------------------------- units

common() {  # shared [Service] body; $1 = spam_filter.py command + args
  cat <<EOF
Type=oneshot
EnvironmentFile=%E/imap-spam-filter/service.env
EnvironmentFile=%E/imap-spam-filter/accounts/%i.conf
Environment=SPAM_FILTER_DATA_DIR=%S/imap-spam-filter/%i
Environment="SPAM_FILTER_APPROVE_CMD=imap-spam-filter approve %i"
Environment=NO_COLOR=1 PYTHONUNBUFFERED=1
StateDirectory=imap-spam-filter/%i
StateDirectoryMode=0700
# Decrypted by systemd into a private, per-run tmpfs only this service can read.
LoadCredentialEncrypted=imap-password:%E/imap-spam-filter/creds/%i.cred
ExecStart=/usr/bin/flock %S/imap-spam-filter/%i/.lock $PYTHON $APP_DIR/spam_filter.py $1
TimeoutStartSec=45min
Nice=10
IOSchedulingClass=idle
UMask=0077
NoNewPrivileges=yes
EOF
}

{ cat <<EOF
[Unit]
Description=IMAP spam filter: classify mail for account %i
Documentation=file://$APP_DIR/README.md
After=network-online.target
ConditionPathExists=%E/imap-spam-filter/accounts/%i.conf

[Service]
EOF
  common 'classify $CLASSIFY_ARGS'
} > "$UNIT_DIR/imap-spam-filter@.service"

cat > "$UNIT_DIR/imap-spam-filter@.timer" <<'EOF'
[Unit]
Description=IMAP spam filter: periodic check for account %i

[Timer]
# First run shortly after the timer starts, then N minutes after each run ends
# (so runs never overlap). Per-account interval: imap-spam-filter@NAME.timer.d/
OnActiveSec=2min
OnUnitInactiveSec=15min
RandomizedDelaySec=30s

[Install]
WantedBy=timers.target
EOF

{ cat <<EOF
[Unit]
Description=IMAP spam filter: learn spam profile for account %i
Documentation=file://$APP_DIR/README.md
After=network-online.target
ConditionPathExists=%E/imap-spam-filter/accounts/%i.conf

[Service]
EOF
  common 'learn $LEARN_ARGS'
} > "$UNIT_DIR/imap-spam-filter-learn@.service"

cat > "$UNIT_DIR/imap-spam-filter-learn@.timer" <<'EOF'
[Unit]
Description=IMAP spam filter: weekly re-learn for account %i

[Timer]
OnCalendar=Sun 03:00
Persistent=true
RandomizedDelaySec=30min

[Install]
WantedBy=timers.target
EOF

systemctl --user daemon-reload

info "pulling $SPAM_FILTER_MODEL on $SPAM_OLLAMA_URL (skipped if up to date)"
OLLAMA_HOST="$SPAM_OLLAMA_URL" "$OLLAMA_BIN" pull "$SPAM_FILTER_MODEL" \
  || die "could not pull $SPAM_FILTER_MODEL"

# Restart timers of existing accounts so they pick up the new units.
shopt -s nullglob
accounts=("$CONF_DIR"/accounts/*.conf)
for f in "${accounts[@]}"; do
  n=$(basename "$f" .conf)
  systemctl --user try-restart "imap-spam-filter@$n.timer" "imap-spam-filter-learn@$n.timer" 2>/dev/null || true
done

echo
info "${G}installed${N}"
echo "   program   $APP_DIR/spam_filter.py"
echo "   command   $BIN_DIR/imap-spam-filter"
echo "   units     $UNIT_DIR/imap-spam-filter{,-learn}@.{service,timer}"
echo "   model     $SPAM_FILTER_MODEL on $SPAM_OLLAMA_URL"
echo
if (( ${#accounts[@]} )); then
  echo "   ${#accounts[@]} existing account(s) updated:  ${B}imap-spam-filter list${N}"
else
  echo "   next:  ${B}imap-spam-filter add <name>${N}     e.g.  imap-spam-filter add personal"
fi
[[ ":$PATH:" == *":$BIN_DIR:"* ]] || warn "$BIN_DIR is not on your PATH"
